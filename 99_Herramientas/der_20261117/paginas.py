def A(s):
    """'*id_x, nombre, ~subtotal, #id_det'  -> * clave, # discriminador, ~ derivado"""
    out = []
    for t in [x.strip() for x in s.split(",")]:
        if t.startswith("*"): out.append((t[1:], "k"))
        elif t.startswith("#"): out.append((t[1:], "d"))
        elif t.startswith("~"): out.append((t[1:], "v"))
        else: out.append((t, "n"))
    return out

